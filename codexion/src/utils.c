#include "../codexion.h"

int	validate_number(const char *s)
{
	int	i;

	if (!strlen(s))
		return (0);
	i = 0;
	while (s[i])
	{
		if (!(s[i] >= '0' && s[i] <= '9'))
			return (0);
		i++;
	}
	return (1);
}
